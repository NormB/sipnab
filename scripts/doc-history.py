#!/usr/bin/env python3
"""Write the release each docs page's source file last changed in.

pages.yml runs this at deploy time, before `zola build`, and
`website/templates/page.html` reads the file it writes to state, under every
docs page, the release that holds the last change to the page's source.
Nothing commits the file: a committed date could only describe the commit
before the one that wrote it.

The rules:

- A page's source is the `source` value in its front matter's `[extra]`
  table (the site generators write it on every page they generate), or the
  page's own file under the content directory when it has none.
- Its last change is the newest commit that touched that path
  (`git log -1 -- PATH`), and the date is that commit's committer date.
- The release is the earliest tag of the form vX.Y.Z that contains that
  commit. When no such tag contains it, the change is in no release yet, and
  the entry names the newest vX.Y.Z tag instead, as `after`.
- A source path with no commit at all is an error: the footer would have
  nothing true to say about it.

The checkout must hold the full history and the tags (`fetch-depth: 0`).

Usage:
    doc-history.py [--repo DIR] [--content DIR] [--write PATH]

--repo defaults to the current directory and --content to
website/content under it. Prints the TOML; with --write, also writes it to
PATH, creating its directory. Exits 1, writing nothing, on an error.
"""

import argparse
import pathlib
import re
import subprocess
import sys
import tomllib

RELEASE = re.compile(r"^v\d+\.\d+\.\d+$")


class HistoryError(Exception):
    """A page's source has no history to state."""


def git(repo, *args) -> str:
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise HistoryError(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def releases(repo, *args) -> list:
    """vX.Y.Z tags, oldest version first, narrowed by extra `git tag` args."""
    out = git(repo, "tag", "--list", "v*", "--sort=v:refname", *args)
    return [t for t in out.split() if RELEASE.match(t)]


def last_change(repo, path: str) -> dict:
    """`{"date", "release"}`, or `{"date", "after"}` when in no release."""
    line = git(repo, "log", "-1", "--format=%H %cs", "--", path).strip()
    if not line:
        raise HistoryError(f"{path} has no commit")
    sha, date = line.split()
    holding = releases(repo, "--contains", sha)
    if holding:
        return {"date": date, "release": holding[0]}
    every = releases(repo)
    if not every:
        raise HistoryError(f"{path}: the repository has no vX.Y.Z tag")
    return {"date": date, "after": every[-1]}


def page_source(rel: str, text: str) -> str:
    """The source file of the content page at `rel` (relative to content/)."""
    if text.startswith("+++"):
        head = text[3:].split("\n+++", 1)[0]
        source = tomllib.loads(head).get("extra", {}).get("source")
        if source:
            return source
    return f"website/content/{rel}"


def page_sources(content) -> set:
    """The source of every page under `content`, section indexes excluded."""
    content = pathlib.Path(content)
    out = set()
    for p in sorted(content.rglob("*.md")):
        if p.name == "_index.md":
            continue
        out.add(page_source(p.relative_to(content).as_posix(), p.read_text()))
    return out


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries: dict) -> str:
    lines = ["# Generated by scripts/doc-history.py at deploy time. Not committed."]
    for path in sorted(entries):
        e = entries[path]
        lines += ["", f"[pages.{toml_str(path)}]", f"date = {toml_str(e['date'])}"]
        if "release" in e:
            lines.append(f"release = {toml_str(e['release'])}")
        else:
            lines.append(f"after = {toml_str(e['after'])}")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=".", help="the git checkout (default: .)")
    ap.add_argument("--content", help="the site content directory (default: REPO/website/content)")
    ap.add_argument("--write", metavar="PATH", help="write the TOML here")
    args = ap.parse_args(argv)
    repo = pathlib.Path(args.repo)
    content = pathlib.Path(args.content) if args.content else repo / "website/content"
    try:
        entries = {src: last_change(repo, src) for src in page_sources(content)}
    except (HistoryError, tomllib.TOMLDecodeError) as e:
        print(f"doc-history: {e}", file=sys.stderr)
        return 1
    text = render(entries)
    if args.write:
        path = pathlib.Path(args.write)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
