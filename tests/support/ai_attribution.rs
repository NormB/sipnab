//! The one rule for a line that credits an AI assistant as an author.
//!
//! Two gates used to carry their own copies: `no_commit_attribution_test`
//! over recent commit messages, and class H of `private_identity_test`, which
//! the commit-msg hook, the pre-push hook and CI's pull-request check all run
//! through `scripts/check-message-identity.sh`. The copies drifted. One named
//! two assistants only, so a co-author trailer naming any other passed the
//! hook and CI; the other required the trailer key at the very start of the
//! line, so the same trailer behind a leading `#` passed it. Both gates now
//! mount this file.
//!
//! The assistant list is at least as wide as the one the LSP repositories'
//! attribution scan refuses. Strings that would match the rule
//! themselves are assembled at run time, so the tracked-file scan finds
//! nothing to exempt here.
#![allow(dead_code)]

use regex::Regex;

/// AI assistants and their vendors, as a regex alternation of whole words.
///
/// `ai` is a whole word only, so "email" and "maintainer" do not match. The
/// bots that author dependency and security updates are not on it.
const TOOLS: &str = r"(claude|anthropic|copilot|chatgpt|openai|gpt-?\d|gemini|codex|cursor|devin|aider|codeium|tabnine|codewhisperer|ai)";

/// The compiled rules, built once per test binary.
struct Rules {
    /// A credit trailer naming an assistant anywhere after its key. The key
    /// starts the line, after any comment or list markers (`#`, `//`, `--`,
    /// `*`, `;`, `>`), so prose that describes the rule is not one.
    trailer: Regex,
    /// "generated with" or "generated by" with an assistant among the next
    /// three words: a vendor's name may come between, but CONTRIBUTING's
    /// description of a footer, which names no assistant that soon, passes.
    footer: Regex,
    /// Substrings that are an attribution wherever they appear.
    anywhere: [String; 3],
}

/// The compiled rules, or the reason one did not compile.
fn rules() -> Result<&'static Rules, &'static regex::Error> {
    static RULES: std::sync::OnceLock<Result<Rules, regex::Error>> = std::sync::OnceLock::new();
    RULES.get_or_init(build_rules).as_ref()
}

fn build_rules() -> Result<Rules, regex::Error> {
    Ok(Rules {
        trailer: Regex::new(&format!(
            r"^[#/\-*;>\s]*(co-authored-by|assisted-by|generated-by):.*\b{TOOLS}\b"
        ))?,
        footer: Regex::new(&format!(
            r"\bgenerated (with|by)\W+(\w+\W+){{0,2}}{TOOLS}\b"
        ))?,
        anywhere: [
            ["noreply", "@anthropic.com"].concat(),
            ["claude", ".ai/code"].concat(),
            ["claude", ".ai/chat"].concat(),
        ],
    })
}

/// Whether one line credits an AI assistant as an author.
///
/// Matched in any case, and behind leading `#` characters: `git commit -m`
/// keeps a line that starts with `#`, so a commented-out credit is still
/// published. The forms:
///
/// * a credit trailer key (`Co-Authored-By`, `Assisted-By`, `Generated-By`)
///   followed by an assistant's name, the key starting the line after any
///   comment or list markers, so a credit behind `//` or `--` is one too;
/// * the session trailer the vendor's tool writes;
/// * the assistant vendor's noreply address, or a link into its session
///   console, anywhere in the line;
/// * "generated with" or "generated by" with an assistant's name among the
///   next three words.
///
/// A product name on its own is not a credit: Claude Code and Claude Desktop
/// are MCP clients the documentation has to name.
#[must_use]
pub fn is_ai_attribution_line(line: &str) -> bool {
    let l = line.to_lowercase();
    // A rule that does not compile refuses every line: the gate fails closed,
    // and the people-and-bots control test turns red at once.
    let Ok(r) = rules() else {
        return true;
    };
    r.trailer.is_match(&l)
        || l.contains(&["claude", "-session:"].concat())
        || r.anywhere.iter().any(|s| l.contains(s.as_str()))
        || r.footer.is_match(&l)
}

/// Whether any line of `message` credits an AI assistant.
#[must_use]
pub fn message_attributes_an_ai(message: &str) -> bool {
    message.lines().any(is_ai_attribution_line)
}
